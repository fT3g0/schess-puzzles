"""Prototype an attention-node search for move-execution difficulty.

A node is a consciously inspected candidate or a plan-changing defense, not a legal
move generated by the program. Forced transitions and latent candidate ranking are
free. The search is intentionally shallow and transparent.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import sys
from functools import lru_cache
from dataclasses import dataclass, field
from pathlib import Path

import pyffish

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from forcingness_analysis import VALUES, attack_map, board_from_fen, move_features


MAX_TIERS = 3
MAX_ALTERNATIVES_PER_TIER = 3
MAX_DEFENSES = 2
DEFAULT_DEPTH = 3
FAIL_MARGIN = 200
SUCCESS_MARGIN = 200


@dataclass
class Attention:
    candidate_nodes: int = 0
    critical_defense_nodes: int = 0
    tier_descents: int = 0
    forced_transitions: int = 0
    cashout_certificates: int = 0
    provisional_certificates: int = 0
    trace: list[str] = field(default_factory=list)

    @property
    def nodes(self) -> int:
        return self.candidate_nodes + self.critical_defense_nodes


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "input",
        type=Path,
        nargs="?",
        default=Path("data/complexity/lichess_transition_probe_500.json"),
    )
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument("--depth", type=int, default=DEFAULT_DEPTH)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("data/complexity/lichess_attention_probe.json"),
    )
    return parser.parse_args()


def subset(profiles: list[dict], limit: int) -> list[dict]:
    if not limit or limit >= len(profiles):
        return profiles
    return sorted(profiles, key=lambda item: hashlib.sha1(item["PuzzleId"].encode()).hexdigest())[:limit]


def material(fen: str, perspective_white: bool) -> int:
    total = 0
    for piece in board_from_fen(fen).values():
        if piece.upper() == "K":
            continue
        value = VALUES.get(piece.upper(), 0) * 100
        total += value if piece.isupper() == perspective_white else -value
    return total


def in_check(fen: str, white: bool) -> bool:
    board = board_from_fen(fen)
    king = next((square for square, piece in board.items() if piece == ("K" if white else "k")), "")
    return bool(king and king in attack_map(board, not white))


def hanging(fen: str, owner_white: bool) -> int:
    board = board_from_fen(fen)
    attacks = attack_map(board, not owner_white)
    defenders = attack_map(board, owner_white)
    values = []
    for square, piece in board.items():
        if piece.isupper() != owner_white or piece.upper() == "K" or square not in attacks:
            continue
        victim = VALUES.get(piece.upper(), 0) * 100
        attacker = min(VALUES.get(board[source].upper(), 0) * 100 for source in attacks[square])
        values.append(victim if square not in defenders else max(0, victim - attacker))
    return max(values, default=0)


def static_score(fen: str, perspective_white: bool) -> int:
    result = material(fen, perspective_white)
    result += hanging(fen, not perspective_white) - hanging(fen, perspective_white)
    if in_check(fen, perspective_white):
        result -= 120
    if in_check(fen, not perspective_white):
        result += 120
    return result


def forcing_moves(fen: str) -> int:
    board = board_from_fen(fen)
    white = fen.split()[1] == "w"
    return sum(move_features(fen, board, move, white)["level"] >= 2 for move in pyffish.legal_moves("chess", fen, []))


def terminal(fen: str, perspective_white: bool) -> str:
    legal = pyffish.legal_moves("chess", fen, [])
    if legal:
        return ""
    side_white = fen.split()[1] == "w"
    if in_check(fen, side_white):
        return "mate_win" if side_white != perspective_white else "mate_loss"
    return "draw"


def cashout(fen: str, perspective_white: bool) -> str:
    margin = material(fen, perspective_white)
    leader_white = perspective_white if margin > 0 else not perspective_white
    if abs(margin) >= 500 and not in_check(fen, leader_white) and forcing_moves(fen) <= 2 and hanging(fen, leader_white) < 300:
        return "major_material"
    if abs(margin) >= 300 and forcing_moves(fen) == 0 and hanging(fen, leader_white) == 0:
        return "quiet_material"
    return ""


def promotion_pressure(fen: str, white: bool) -> int:
    board = board_from_fen(fen)
    best = 0
    for square, piece in board.items():
        if piece != ("P" if white else "p"):
            continue
        rank = int(square[1])
        steps = 8 - rank if white else rank - 1
        if steps > 3:
            continue
        blocked_by_pawn = any(
            other.upper() == "P" and other.isupper() != white and other_square[0] == square[0]
            and ((int(other_square[1]) > rank) if white else (int(other_square[1]) < rank))
            for other_square, other in board.items()
        )
        best = max(best, max(0, 4 - steps) + (1 if not blocked_by_pawn else 0))
    return best

def king_attack_units(fen: str, white: bool) -> int:
    board = board_from_fen(fen)
    enemy_king = next((square for square, piece in board.items() if piece == ("k" if white else "K")), "")
    if not enemy_king:
        return 0
    file, rank = ord(enemy_king[0]) - 97, int(enemy_king[1]) - 1
    zone = {f"{chr(97 + x)}{y + 1}" for x in range(max(0, file - 1), min(8, file + 2)) for y in range(max(0, rank - 1), min(8, rank + 2))}
    attacks = attack_map(board, white)
    return sum(len(attacks.get(square, [])) for square in zone)

def compensation_after_recapture(fen: str, solver_white: bool, debt: int) -> dict:
    board = board_from_fen(fen)
    moves = pyffish.legal_moves("chess", fen, [])
    features = [move_features(fen, board, move, solver_white) for move in moves]
    checks = sum(feature["level"] >= 3 for feature in features)
    max_threat = max((feature["material_threat_value"] for feature in features), default=0)
    pressure = promotion_pressure(fen, solver_white)
    attack = king_attack_units(fen, solver_white)
    viable = (checks >= 1 and (attack >= 2 or pressure >= 2 or max_threat >= 3)) or pressure >= 3 or max_threat >= debt
    return {"checks": checks, "max_threat": max_threat, "promotion_pressure": pressure, "king_attack": attack, "viable": viable}

@lru_cache(maxsize=100000)
def candidate_tiers(fen: str) -> list[list[dict]]:
    board = board_from_fen(fen)
    white = fen.split()[1] == "w"
    legal = pyffish.legal_moves("chess", fen, [])
    records = []
    for move in legal:
        feature = move_features(fen, board, move, white)
        priority = feature["captured_value"] * 80 + feature["material_threat_value"] * 60
        status = "safe"
        debt = 0
        if feature["level"] >= 2:
            after = pyffish.get_fen("chess", fen, [move])
            moved = feature["after_board"][move[2:4]]
            debt = 0 if moved.upper() == "K" else max(0, VALUES.get(moved.upper(), 0) - feature["captured_value"])
            recaptures = [reply for reply in pyffish.legal_moves("chess", after, []) if reply[2:4] == move[2:4]]
            if not recaptures:
                debt = 0
            if debt >= 2 and recaptures:
                profiles = [compensation_after_recapture(pyffish.get_fen("chess", after, [reply]), white, debt) for reply in recaptures]
                status = "conditional" if all(profile["viable"] for profile in profiles) else "refuted"
        effective_tier = feature["level"] if status != "refuted" else min(1, feature["level"])
        records.append({
            "move": move,
            "tier": effective_tier,
            "raw_tier": feature["level"],
            "priority": priority,
            "feature": feature,
            "debt": debt,
            "status": status,
        })
    records.sort(key=lambda item: (-item["tier"], -item["priority"], item["move"]))
    groups: list[list[dict]] = []
    for tier in sorted({item["tier"] for item in records}, reverse=True):
        groups.append([item for item in records if item["tier"] == tier][:MAX_ALTERNATIVES_PER_TIER])
    return groups[:MAX_TIERS]


def critical_defenses(fen: str, solver_white: bool) -> tuple[list[dict], bool]:
    legal = pyffish.legal_moves("chess", fen, [])
    if len(legal) == 1:
        return [{"move": legal[0], "forced": True}], True
    board = board_from_fen(fen)
    side_white = fen.split()[1] == "w"
    # Several ordinary king escapes after a check usually form one human response
    # class: the attacker only needs to see that the king must move away.
    if in_check(fen, side_white) and all(board[move[:2]].upper() == "K" for move in legal):
        return [{"move": legal[0], "forced": True}], True
    groups = candidate_tiers(fen)
    candidates = groups[0] if groups else []
    # Quiet moves are not automatically critical defenses. They enter only after a
    # separate threat/positional model can show that they break the attacker's plan.
    if not candidates or candidates[0]["tier"] == 0:
        return [], False
    return candidates[:MAX_DEFENSES], False


def provisional_forcing_certificate(after_fen: str, feature: dict, solver_white: bool) -> bool:
    """Cheap visual reason to accept a dominant first candidate provisionally."""
    if feature["level"] < 3:
        return False
    replies, forced = critical_defenses(after_fen, solver_white)
    if not forced or not replies:
        return False
    reply_fen = pyffish.get_fen("chess", after_fen, [replies[0]["move"]])
    own_tiers = candidate_tiers(reply_fen)
    if not own_tiers:
        return False
    own_top = own_tiers[0]
    return bool(own_top and (own_top[0]["tier"] >= 2 or own_top[0]["feature"]["material_threat_value"] >= 3))


def assess_candidate(
    fen: str,
    candidate: dict,
    solver_white: bool,
    baseline: int,
    depth: int,
    attention: Attention,
) -> str:
    """Return success, fail, or uncertain for one consciously checked candidate."""
    attention.candidate_nodes += 1
    move = candidate["move"]
    attention.trace.append(f"candidate depth={depth} tier={candidate['tier']} status={candidate['status']} debt={candidate['debt']} {move}")
    after = pyffish.get_fen("chess", fen, [move])
    end = terminal(after, solver_white)
    if end == "mate_win":
        attention.cashout_certificates += 1
        return "success"
    if end == "mate_loss":
        return "fail"
    certificate = cashout(after, solver_white)
    if certificate:
        attention.cashout_certificates += 1
        return "success"
    # A safe high-value capture with no forcing reply is a visible tactical cash-out.
    immediate_defenses, _ = critical_defenses(after, solver_white)
    if (candidate["feature"]["captured_value"] >= 3 or candidate["feature"]["material_threat_value"] >= 3) and not immediate_defenses:
        attention.cashout_certificates += 1
        attention.trace.append(f"visible_cashout {move}")
        return "success"

    if provisional_forcing_certificate(after, candidate["feature"], solver_white):
        attention.provisional_certificates += 1
        return "success"
    if depth <= 0:
        delta = static_score(after, solver_white) - baseline
        return "success" if delta >= SUCCESS_MARGIN else "fail" if delta <= -FAIL_MARGIN else "uncertain"

    defenses, forced = critical_defenses(after, solver_white)
    branch_statuses = []
    for defense in defenses:
        if forced:
            attention.forced_transitions += 1
            attention.trace.append(f"forced reply {defense['move']}")
        else:
            attention.critical_defense_nodes += 1
            attention.trace.append(f"defense {defense['move']}")
        defended = pyffish.get_fen("chess", after, [defense["move"]])
        status = solve_position(defended, solver_white, baseline, depth - 1, attention)
        branch_statuses.append(status)
    if "fail" in branch_statuses:
        return "fail"
    if branch_statuses and all(status == "success" for status in branch_statuses):
        return "success"
    return "uncertain"


def solve_position(fen: str, solver_white: bool, baseline: int, depth: int, attention: Attention) -> str:
    end = terminal(fen, solver_white)
    if end == "mate_win":
        attention.cashout_certificates += 1
        return "success"
    if end == "mate_loss":
        return "fail"
    certificate = cashout(fen, solver_white)
    if certificate:
        attention.cashout_certificates += 1
        return "success"
    # Do not search on after an obvious material collapse unless the solver has an
    # immediate checking continuation. This rejects visibly refuted sacrifices
    # before they create a large artificial subtree.
    if static_score(fen, solver_white) - baseline <= -FAIL_MARGIN:
        tiers_for_reply = candidate_tiers(fen)
        top_tier = tiers_for_reply[0][0]["tier"] if tiers_for_reply and tiers_for_reply[0] else 0
        if top_tier < 3:
            attention.trace.append("obvious material refutation")
            return "fail"

    if depth <= 0:
        delta = static_score(fen, solver_white) - baseline
        return "success" if delta >= SUCCESS_MARGIN else "fail" if delta <= -FAIL_MARGIN else "uncertain"

    tiers = candidate_tiers(fen)
    for tier_index, tier in enumerate(tiers):
        if tier_index:
            attention.tier_descents += 1
            attention.trace.append(f"tier descent to {tier_index}")
        for candidate in tier:
            status = assess_candidate(fen, candidate, solver_white, baseline, depth, attention)
            if status == "success":
                return "success"
        # An unresolved natural candidate makes the current tier genuinely costly.
        # Continue downward only after every candidate in this tier lacked a proof.
    return "uncertain"


def profile(profile: dict, depth: int) -> dict:
    moves = profile["Moves"].split()
    decisions = []
    for node in profile["nodes"]:
        ply = int(node["ply"])
        fen = pyffish.get_fen("chess", profile["InitialFEN"], moves[:ply])
        solver_white = fen.split()[1] == "w"
        attention = Attention()
        status = solve_position(fen, solver_white, static_score(fen, solver_white), depth, attention)
        decisions.append({
            "ply": ply,
            "solution_uci": node["solution_uci"],
            "status": status,
            "attention_nodes": attention.nodes,
            "candidate_nodes": attention.candidate_nodes,
            "critical_defense_nodes": attention.critical_defense_nodes,
            "tier_descents": attention.tier_descents,
            "forced_transitions": attention.forced_transitions,
            "cashout_certificates": attention.cashout_certificates,
            "provisional_certificates": attention.provisional_certificates,
            "trace": attention.trace,
        })
    metrics = {
        key: sum(item[key] for item in decisions)
        for key in ("attention_nodes", "candidate_nodes", "critical_defense_nodes", "tier_descents", "forced_transitions", "cashout_certificates", "provisional_certificates")
    }
    metrics["attention_success_rate"] = round(sum(item["status"] == "success" for item in decisions) / len(decisions), 3)
    profile["attention_search"] = {"decisions": decisions, "metrics": metrics}
    profile["metrics"].update(metrics)
    return profile


def spearman(values: list[float], ratings: list[float]) -> float:
    order = lambda items: [sorted(range(len(items)), key=lambda index: items[index]).index(index) + 1 for index in range(len(items))]
    left, right = order(values), order(ratings)
    left_mean, right_mean = sum(left) / len(left), sum(right) / len(right)
    denominator = math.sqrt(sum((value - left_mean) ** 2 for value in left) * sum((value - right_mean) ** 2 for value in right))
    return round(sum((a - left_mean) * (b - right_mean) for a, b in zip(left, right)) / denominator, 3) if denominator else 0.0


def main() -> None:
    args = parse_args()
    report = json.loads(args.input.read_text(encoding="utf-8"))
    completed = []
    for index, item in enumerate(subset(report["profiles"], args.limit), start=1):
        try:
            completed.append(profile(item, args.depth))
            metrics = completed[-1]["metrics"]
            print(f"[{index}] {item['PuzzleId']}: rating={item['Rating']} attention={metrics['attention_nodes']} success={metrics['attention_success_rate']}")
        except Exception as exc:
            print(f"skip {item['PuzzleId']}: {exc}")
    report["profiles"] = completed
    metrics = ["attention_nodes", "candidate_nodes", "critical_defense_nodes", "tier_descents", "cashout_certificates", "provisional_certificates"]
    ratings = [float(item["Rating"]) for item in completed]
    report["attention_search_definition"] = {
        "node": "consciously inspected candidate or non-forced, plan-changing defense; forced transitions and latent ranking are free",
        "candidate_fallback": "activate a forcing tier first; descend only once that tier has no success certificate",
        "certificates": "terminal, quiet/major material conversion, or a forced check leading to visible forcing or material-threat continuations",
        "depth": args.depth,
    }
    report["attention_search_correlations"] = {
        metric: spearman([float(item["metrics"][metric]) for item in completed], ratings)
        for metric in metrics
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print("Attention correlations:", report["attention_search_correlations"])
    print(f"Wrote {args.output} for {len(completed)} puzzle(s).")


if __name__ == "__main__":
    main()
